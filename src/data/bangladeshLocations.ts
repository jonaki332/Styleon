export function findDistrictEntry(input: string): DistrictEntry | null {
  const query = input.trim().toLowerCase();
  if (!query) return null;
  return (
    BANGLADESH_DISTRICTS.find(
      (d) => d.district.toLowerCase() === query || d.districtBn === input.trim(),
    ) ?? null
  );
}

export function isValidDistrictUpazila(
  districtName: string,
  upazilaName: string,
): boolean {
  const entry = findDistrictEntry(districtName);
  if (!entry) return false;
  const trimmed = upazilaName.trim();
  const lowered = trimmed.toLowerCase();
  if (!lowered) return false;
  return entry.upazilas.some(
    (u) => u.name.toLowerCase() === lowered || u.nameBn === trimmed,
  );
}
